namespace content = aowis::db::content_store;
namespace tree = aowis::db::merkle_tree;
using aowis::db::PostgresBackend;
using aowis::db::SqliteBackend;

#define REQUIRE(condition) do { \
    if (!(condition)) { \
        qCritical().noquote() << "FAILED" << __FILE__ << __LINE__ << #condition << error; \
        return false; \
    } \
} while (false)

QUuid keyFromHex(const char *hex)
{
    return QUuid::fromRfc4122(QByteArray::fromHex(QByteArray(hex)));
}

std::optional<QByteArray> blob(const QSqlDatabase &database, const QByteArray &bytes,
                               QString &error)
{
    return content::put(database, content::Kind::Blob, bytes, &error);
}

bool exercise(const QSqlDatabase &database, QString &error)
{
    const QUuid a = keyFromHex("0102030405060708090a0b0c0d0e0f10");
    const QUuid b = keyFromHex("0102030405060708090a0b0c0d0e0f11");
    const QUuid c = keyFromHex("0102030405060708090a0b0c0d0e0f20");
    const QUuid d = keyFromHex("f102030405060708090a0b0c0d0e0f10");
    const QUuid absent = keyFromHex("0102030405060708090a0b0c0d0e0f21");
    const std::optional<QByteArray> x = blob(database, QByteArray("same contents"), error);
    const std::optional<QByteArray> y = blob(database, QByteArray("new contents"), error);
    REQUIRE(x.has_value() && y.has_value());

    const std::optional<QByteArray> empty = tree::emptyRoot(database, &error);
    REQUIRE(empty && empty->size() == 32);
    // Independent binary-encoding test vectors, not generated by this API.
    REQUIRE(empty->toHex() == QByteArray(
        "82203c7480a005551fb0af15ae0e21a9ae8f51791e04d3008954628b906f38c5"));
    REQUIRE(tree::emptyRoot(database, &error) == empty);
    const std::optional<QVector<tree::Entry>> nothing = tree::entries(database, *empty, &error);
    REQUIRE(nothing && nothing->isEmpty());
    REQUIRE(!tree::lookup(database, *empty, a, &error) && error.isEmpty());
    REQUIRE(tree::update(database, *empty, tree::Change{a, std::nullopt}, &error) == empty);

    // The first insertion creates a compressed leaf. A nearby UUID forks
    // deeply, and a distant UUID forks near the root.
    const std::optional<QByteArray> root_a = tree::update(
        database, *empty, tree::Change{a, *x}, &error);
    REQUIRE(root_a && *root_a != *empty);
    REQUIRE(root_a->toHex() == QByteArray(
        "16dba4c72d2a5283f350cae72bf91b07ed8779b9e5d44c2a66379a7bfb778386"));
    REQUIRE(tree::lookup(database, *root_a, a, &error) == x);
    REQUIRE(tree::lookup(database, *root_a, b, &error) == std::nullopt && error.isEmpty());
    const std::optional<QByteArray> root_ab = tree::update(
        database, *root_a, tree::Change{b, *x}, &error);
    REQUIRE(root_ab && *root_ab != *root_a);
    const std::optional<QByteArray> root_abc = tree::update(
        database, *root_ab, tree::Change{c, *x}, &error);
    REQUIRE(root_abc && *root_abc != *root_ab);
    const std::optional<QByteArray> root_abcd = tree::update(
        database, *root_abc, tree::Change{d, *y}, &error);
    REQUIRE(root_abcd && *root_abcd != *root_abc);
    REQUIRE(tree::lookup(database, *root_abcd, d, &error) == y);
    REQUIRE(tree::lookup(database, *root_abcd, b, &error) == x);
    REQUIRE(tree::lookup(database, *root_abcd, absent, &error) == std::nullopt);
    REQUIRE(error.isEmpty());
    REQUIRE(tree::update(database, *root_abcd, tree::Change{a, *x}, &error) == root_abcd);
    REQUIRE(tree::update(database, *root_abcd, tree::Change{absent, std::nullopt}, &error) == root_abcd);

    // Updating one UUID creates a new root, but old roots stay readable.
    const std::optional<QByteArray> changed = tree::update(
        database, *root_abcd, tree::Change{a, *y}, &error);
    REQUIRE(changed && *changed != *root_abcd);
    REQUIRE(tree::lookup(database, *changed, a, &error) == y);
    REQUIRE(tree::lookup(database, *root_abcd, a, &error) == x);
    REQUIRE(tree::lookup(database, *root_a, a, &error) == x);
    REQUIRE(tree::lookup(database, *changed, c, &error) == x);
    const std::optional<QByteArray> restored = tree::update(
        database, *changed, tree::Change{a, *x}, &error);
    REQUIRE(restored == root_abcd); // Deterministic content-addressed roots.

    // Deletions collapse compressed paths into canonical trees: insertion
    // history does not affect the root for the same logical UUID->hash map.
    const std::optional<QByteArray> remove_d = tree::update(
        database, *root_abcd, tree::Change{d, std::nullopt}, &error);
    REQUIRE(remove_d == root_abc);
    const std::optional<QByteArray> remove_c = tree::update(
        database, *remove_d, tree::Change{c, std::nullopt}, &error);
    REQUIRE(remove_c == root_ab);
    const std::optional<QByteArray> remove_b = tree::update(
        database, *remove_c, tree::Change{b, std::nullopt}, &error);
    REQUIRE(remove_b == root_a);
    REQUIRE(tree::update(database, *remove_b, tree::Change{a, std::nullopt}, &error) == empty);

    const QVector<tree::Change> first_batch{{d, *y}, {c, *x}, {a, *x}, {b, *x}};
    const QVector<tree::Change> reverse_batch{{b, *x}, {a, *x}, {d, *y}, {c, *x}};
    REQUIRE(tree::apply(database, *empty, first_batch, &error) == root_abcd);
    REQUIRE(tree::apply(database, *empty, reverse_batch, &error) == root_abcd);
    REQUIRE(tree::build(database, first_batch, &error) == root_abcd);
    REQUIRE(tree::build(database, reverse_batch, &error) == root_abcd);
    REQUIRE(tree::build(database, {}, &error) == empty);
    REQUIRE(tree::build(database, {{a, *x}}, &error) == root_a);
    REQUIRE(!tree::build(database, {{a, *x}, {a, *y}}, &error));
    REQUIRE(error.contains(QStringLiteral("Duplicate")));
    error.clear();
    REQUIRE(!tree::build(database, {{a, std::nullopt}}, &error));
    REQUIRE(error.contains(QStringLiteral("requires")));
    error.clear();
    REQUIRE(!tree::build(database, {{a, QByteArray(32, 'z')}}, &error));
    REQUIRE(error.contains(QStringLiteral("not found")));
    error.clear();
    REQUIRE(!tree::apply(database, *empty, {{a, *x}, {a, *y}}, &error));
    REQUIRE(error.contains(QStringLiteral("Duplicate")));
    error.clear();
    REQUIRE(!tree::update(database, *root_abcd,
                          tree::Change{a, QByteArray(32, 'z')}, &error));
    REQUIRE(error.contains(QStringLiteral("not found")));
    error.clear();
    REQUIRE(!tree::update(database, *root_abcd,
                          tree::Change{a, QByteArray(31, 'z')}, &error));
    REQUIRE(!error.isEmpty());
    error.clear();
    REQUIRE(!tree::lookup(database, QByteArray(32, 'z'), a, &error));
    REQUIRE(!error.isEmpty());
    error.clear();
    const std::optional<QByteArray> malformed = content::put(
        database, content::Kind::Tree, QByteArray("not a Merkle tree"), &error);
    REQUIRE(malformed.has_value());
    REQUIRE(!tree::entries(database, *malformed, &error));
    REQUIRE(error.contains(QStringLiteral("magic")));
    error.clear();

    const std::optional<QVector<tree::Entry>> list = tree::entries(database, *root_abcd, &error);
    REQUIRE(list && list->size() == 4);
    REQUIRE(list->at(0).key == a && list->at(0).blob_sha256 == x);
    REQUIRE(list->at(1).key == b && list->at(1).blob_sha256 == x);
    REQUIRE(list->at(2).key == c && list->at(2).blob_sha256 == x);
    REQUIRE(list->at(3).key == d && list->at(3).blob_sha256 == y);

    // Multiple roots with deep common prefixes: no history replay, no
    // recursion proportional to revision count, and no omitted keys.
    QVector<tree::Change> many;
    for (int i = 0; i < 256; ++i)
    {
        QByteArray bytes = a.toRfc4122();
        bytes[13] = static_cast<char>((i >> 8) & 0xff);
        bytes[14] = static_cast<char>(i & 0xff);
        bytes[15] = static_cast<char>(i ^ 0xa5);
        many.append({QUuid::fromRfc4122(bytes), (i % 2 == 0) ? *x : *y});
    }
    const std::optional<QByteArray> many_root = tree::apply(database, *empty, many, &error);
    REQUIRE(many_root && *many_root != *empty);
    const std::optional<QByteArray> built_root = tree::build(database, many, &error);
    REQUIRE(built_root && built_root == many_root);
    const std::optional<QVector<tree::Entry>> many_list = tree::entries(database, *many_root, &error);
    REQUIRE(many_list && many_list->size() == many.size());
    for (const tree::Change &change : many)
        REQUIRE(tree::lookup(database, *many_root, change.key, &error) == change.blob_sha256);
    REQUIRE(tree::lookup(database, *root_abcd, a, &error) == x);
    const std::optional<QVector<tree::Entry>> still_empty = tree::entries(database, *empty, &error);
    REQUIRE(still_empty && still_empty->isEmpty());

    // A one-object modification must write only the affected search path,
    // not 256 copied leaf records (or rows for every older revision).
    QSqlQuery count_query(database);
    REQUIRE(count_query.exec(QStringLiteral("SELECT COUNT(*) FROM content_objects WHERE kind='tree'")));
    REQUIRE(count_query.next());
    const qint64 before = count_query.value(0).toLongLong();
    count_query.finish();
    const std::optional<QByteArray> forked = tree::update(
        database, *many_root, tree::Change{many.at(127).key, *x}, &error);
    REQUIRE(forked && *forked != *many_root);
    REQUIRE(tree::lookup(database, *forked, many.at(127).key, &error) == x);
    REQUIRE(tree::lookup(database, *many_root, many.at(127).key, &error) == y);
    REQUIRE(count_query.exec(QStringLiteral("SELECT COUNT(*) FROM content_objects WHERE kind='tree'")));
    REQUIRE(count_query.next());
    const qint64 after = count_query.value(0).toLongLong();
    REQUIRE(after - before >= 1 && after - before <= 33);
    count_query.finish();

    // Immutable roots and children are protected by the content-store SQL
    // triggers, even if the tree API is bypassed.
    QSqlQuery query(database);
    REQUIRE(query.exec(QStringLiteral("SAVEPOINT merkle_mutation_check")));
    REQUIRE(query.prepare(QStringLiteral("DELETE FROM content_objects WHERE sha256=?")));
    query.addBindValue(*root_abcd);
    REQUIRE(!query.exec());
    query.finish();
    REQUIRE(query.exec(QStringLiteral("ROLLBACK TO SAVEPOINT merkle_mutation_check")));
    REQUIRE(query.exec(QStringLiteral("RELEASE SAVEPOINT merkle_mutation_check")));
    REQUIRE(tree::lookup(database, *root_abcd, d, &error) == y);
    return true;
}

int main(int argc, char **argv)
{
    QCoreApplication app(argc, argv);
    QString error;
    QTemporaryDir temp;
    if (!temp.isValid())
        return 1;
    const QString path = temp.filePath(QStringLiteral("merkle.sqlite"));
    const SqliteBackend sqlite;
    {
        QSqlDatabase connection;
        if (!sqlite.open(connection, QStringLiteral("merkle-sqlite"), path, &error) ||
            !sqlite.configure(connection, &error) ||
            !sqlite.createSchema(connection, &error) ||
            !sqlite.verifySchema(connection, &error) ||
            !exercise(connection, error))
        {
            qCritical().noquote() << "SQLite Merkle tree test failed:" << error;
            return 1;
        }
        connection.close();
    }
    QSqlDatabase::removeDatabase(QStringLiteral("merkle-sqlite"));

    const QByteArray pg_database_name = qgetenv("AOWIS_DB_TEST_PG_DB");
    if (qgetenv("AOWIS_DB_TEST_PG_REQUIRED") == QByteArray("1") && pg_database_name.isEmpty())
        return 1;
    if (!pg_database_name.isEmpty())
    {
        const PostgresBackend postgres;
        const QString name = QStringLiteral("merkle-postgres");
        {
            QSqlDatabase connection;
            if (!postgres.open(connection, name, QString::fromUtf8(pg_database_name), &error) ||
                !postgres.configure(connection, &error) ||
                !postgres.beginWrite(connection, &error))
            {
                qCritical().noquote() << "PostgreSQL Merkle setup failed:" << error;
                return 1;
            }
            const QString schema = QStringLiteral("aowis_merkle_probe_") +
                QUuid::createUuid().toString(QUuid::Id128);
            QSqlQuery query(connection);
            if (!query.exec(QStringLiteral("CREATE SCHEMA %1").arg(schema)) ||
                !query.exec(QStringLiteral("SET LOCAL search_path TO %1").arg(schema)) ||
                !postgres.createSchema(connection, &error) ||
                !postgres.verifySchema(connection, &error) ||
                !exercise(connection, error))
            {
                qCritical().noquote() << "PostgreSQL Merkle test failed:" << error
                                       << query.lastError().text();
                postgres.rollback(connection);
                return 1;
            }
            query = QSqlQuery();
            postgres.rollback(connection); // transaction-local disposable schema
            connection.close();
        }
        QSqlDatabase::removeDatabase(name);
    }
    return 0;
}
